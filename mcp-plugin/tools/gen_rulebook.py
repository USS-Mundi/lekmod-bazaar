#!/usr/bin/env python3
"""Writes MCPServer/src/McpRulebookData.inc from docs/agent/rulebook.md, so the launcher hands every agent the rulebook
of the plugin it plays. generator/build_mcp.sh runs it before each build.
Usage: tools/gen_rulebook.py [--check]   (--check: exit 1 when the .inc is not the rulebook's)"""
import hashlib, os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "..", "docs", "agent", "rulebook.md")
out = os.path.join(here, "..", "MCPServer", "src", "McpRulebookData.inc")
raw = open(src, encoding="utf-8").read()
def lit(s):
    r = []
    for c in s.encode("utf-8"):
        ch = chr(c)
        if ch in '"\\': r.append("\\" + ch)
        elif 32 <= c < 127 and ch != "?": r.append(ch)   # '?' escaped: no trigraphs
        else: r.append("\\%03o" % c)
    return '"' + "".join(r) + '\\n"'
text = ("// Generated by tools/gen_rulebook.py from docs/agent/rulebook.md; do not edit. sha256 of the source: %s\n"
        % hashlib.sha256(raw.encode()).hexdigest()[:16])
text += "static const char* const kRulebook[] = {\n" + "".join("\t" + lit(l) + ",\n" for l in raw.split("\n")) + "\tNULL\n};\n"
if "--check" in sys.argv[1:]:
    sys.exit(0 if os.path.isfile(out) and open(out, encoding="ascii").read() == text else "McpRulebookData.inc is stale: run tools/gen_rulebook.py")
with open(out, "w", encoding="ascii", newline="\n") as f:
    f.write(text)
print(out)
