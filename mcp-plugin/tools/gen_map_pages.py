#!/usr/bin/env python3
"""Writes MCPServer/src/McpMapPagesData.inc from docs/agent/maps/<map script>.md, so game_settings hands every agent
the page of the map script its game runs on. generator/build_mcp.sh runs it before each build.
Usage: tools/gen_map_pages.py [--check]   (--check: exit 1 when the .inc is not the pages')"""
import glob, hashlib, os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "..", "docs", "agent", "maps")
out = os.path.join(here, "..", "MCPServer", "src", "McpMapPagesData.inc")
def lit(s):
    r = []
    for c in s.encode("utf-8"):
        ch = chr(c)
        if ch in '"\\': r.append("\\" + ch)
        elif 32 <= c < 127 and ch != "?": r.append(ch)   # '?' escaped: no trigraphs
        else: r.append("\\%03o" % c)
    return '"' + "".join(r) + '"'
pages = sorted(glob.glob(os.path.join(src, "*.md")))
if not pages:
    sys.exit("no map pages in %s" % src)
digest = hashlib.sha256()
rows = []
for path in pages:
    raw = open(path, encoding="utf-8").read().strip() + "\n"
    digest.update(raw.encode())
    name = os.path.splitext(os.path.basename(path))[0]
    rows.append("\t{ %s,\n\t  %s },\n" % (lit(name), "\n\t  ".join(lit(l + "\n") for l in raw.rstrip("\n").split("\n"))))
text = ("// Generated by tools/gen_map_pages.py from docs/agent/maps/*.md; do not edit. sha256 of the sources: %s\n"
        % digest.hexdigest()[:16])
text += "static const char* const kMapPages[][2] = {\n" + "".join(rows) + "\t{ NULL, NULL }\n};\n"
if "--check" in sys.argv[1:]:
    sys.exit(0 if os.path.isfile(out) and open(out, encoding="ascii").read() == text else "McpMapPagesData.inc is stale: run tools/gen_map_pages.py")
with open(out, "w", encoding="ascii", newline="\n") as f:
    f.write(text)
print(out)
