#!/usr/bin/env python3
"""Writes MCPServer/src/McpSeedLibraryData.inc from the leader seed library's text, which is not in this repository.
Usage: tools/gen_seed_library.py <path to library.txt>"""
import hashlib, os, sys
if len(sys.argv) < 2: sys.exit(__doc__)
src = sys.argv[1]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "MCPServer", "src", "McpSeedLibraryData.inc")
raw = open(src, encoding="utf-8").read()
def lit(s):
    b = s.encode("utf-8"); r = []
    for c in b:
        ch = chr(c)
        if ch in '"\\': r.append("\\" + ch)
        elif 32 <= c < 127 and ch != "?": r.append(ch)   # '?' escaped: no trigraphs
        else: r.append("\\%03o" % c)
    return '"' + "".join(r) + '"'
rows = [l for l in raw.split("\n") if l.strip() and not l.startswith("#")]
with open(out, "w", encoding="ascii", newline="\n") as f:
    f.write("// Generated by tools/gen_seed_library.py from the leader seed library; do not edit. Lines: %d. sha256 of the source: %s\n"
            % (len(rows), hashlib.sha256(raw.encode()).hexdigest()[:16]))
    f.write("static const char* const kSeedLibrary[] = {\n")
    for l in rows: f.write("\t" + lit(l) + ",\n")
    f.write("};\n")
print(out, len(rows), "lines")
