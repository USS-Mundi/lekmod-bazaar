#pragma once
// The page dealer: deals a seat's first page ("who you are") from the leader seed library and the leaders' rolled
// personality sheets. Pure: the same input and library give the same page, so a reload deals the same person. No game
// headers, so it is tested natively (tests/run_seed_compose_test.sh) against pages dealt by the Python composer it
// was ported from (tests/gen_seed_fixtures.py).
#include <map>
#include <string>
#include <utility>
#include <vector>

enum { MCP_SEED_TRAITS = 12 };
// The twelve traits a page can speak of, in page order: appetite (victory, wonder, minor, boldness), bonds
// (friendship, loyalty, neediness, balance), reaction (forgiveness, warhate, meanness, denounce).
extern const char* const kMcpSeedTraits[MCP_SEED_TRAITS];
// The Leaders table column each trait is read from, in the same order.
extern const char* const kMcpSeedColumns[MCP_SEED_TRAITS];

struct McpSeedLine { std::string id, text; };
// "trait pole form" -> its lines in the library's order; the frame and table lines are under "- - frame" and "- - table".
typedef std::map<std::string, std::vector<McpSeedLine> > McpSeedLibrary;
// Reads library text (columns: sign trait pole form id text). Only lines signed "ok" are taken unless unsignedToo.
void McpSeedLibraryParse(const std::string& text, bool unsignedToo, McpSeedLibrary& lib);
// The signed lines built into the plugin (McpSeedLibraryData.inc, generated by tools/gen_seed_library.py).
const McpSeedLibrary& McpSeedLibraryBuiltIn();

struct McpSeedInput
{
	std::string civ, second;               // second is "" for one leader
	std::vector<int> a, b;                 // rolled sheets in trait order; b is empty for one leader
	std::vector<int> base;                 // one leader: the leader's usual sheet, for "born" lines; empty for none
	std::vector<std::vector<int> > table;  // per trait, twice every other seat's value (a seat with two leaders stands at their mean), for table-relative lines; empty for none
	std::string dealKey;                   // the game and the seat: the same key deals the same page
};

struct McpSeedRecord
{
	std::vector<std::pair<std::string, std::string> > classes;  // trait -> bedrock+ | plain- | fault~ | born+ | unwritten? | table+ ..., in trait order
	std::vector<std::string> ids;                               // the library lines dealt, in page order
	std::vector<std::string> cut;                               // traits that had a line and lost it to the page's limits
	int words;
	McpSeedRecord() : words(0) {}
};

// False with err when the library lacks a line the page needs.
bool McpComposeSeed(const McpSeedInput& in, const McpSeedLibrary& lib, std::string& page, McpSeedRecord& rec, std::string& err);
// The dealer's hash of its parts joined by ':' (the first 48 bits of their SHA-256): never the game's random stream.
unsigned long long McpSeedHash(const std::string& joined);
// A leader's usual value moved by -2 to +2, keyed on (key, leader, trait) and kept within lo..hi.
int McpSeedRoll(int base, const std::string& key, const std::string& leader, const std::string& trait, int lo, int hi);
std::string McpSha256Hex(const std::string& data);
// A civilization's name as it reads after "I rule": peoples and plural names take "the" ("the Franks", "the Maya").
std::string McpSeedThe(const std::string& civName);
// A library line's text by its id, "" when the library has no such line.
std::string McpSeedLineText(const McpSeedLibrary& lib, const std::string& id);
