	void Log(const char* format, ...)
	{
		char line[512];
		va_list args;
		va_start(args, format);
		_vsnprintf_s(line, sizeof(line), _TRUNCATE, format, args);
		va_end(args);
		g_host->Log(g_host->pluginIndex, line);
	}

