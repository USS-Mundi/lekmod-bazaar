	// Works out what applies from the game's setup: whether the option is on, the map seed, and who plays what. Runs
	// before players are set up and before a saved game's traits are read; does nothing when none of that changed.
	// The slots in play when this game began, kept per map seed so a reload still counts a player killed since.
	// Where the pairs record and the agents' file go: a SecondLeaderSettings 'Root' row, else the game's own folder
	// (My Games\Sid Meier's Civilization 5\Second Leader). Looked up when first needed; made when first written to.
	const std::string& Root()
	{
		if(s_root.empty()) s_root = One("SELECT Value FROM SecondLeaderSettings WHERE Name = 'Root'");
		if(s_root.empty())
		{
			std::string games = SlMyGamesFolder();
			if(!games.empty()) s_root = games + "\\Second Leader";
		}
		return s_root;
	}
	void MakeRoot()
	{
		CreateDirectoryA(Root().c_str(), 0);
		CreateDirectoryA((Root() + "/merges").c_str(), 0);
	}

	std::string RecordPath()
	{
		char seed[32];
		_snprintf_s(seed, sizeof(seed), _TRUNCATE, "%u", CvPreGame::mapRandomSeed());
		return Root() + "/merges/pairs-" + seed + ".txt";
	}

	std::string ReadAll(const std::string& path)
	{
		std::string out;
		FILE* f = 0;
		if(fopen_s(&f, path.c_str(), "rb") != 0 || !f) return out;
		char buf[4096];
		size_t n;
		while((n = fread(buf, 1, sizeof(buf), f)) > 0) out.append(buf, n);
		fclose(f);
		return out;
	}

	// Works out what applies from the game's setup: whether the option is on, the map seed, and who plays what. Runs
	// before players are set up and before a saved game's traits are read; does nothing when none of that changed.
	// newGame: the slots in play now are the game's, and they are recorded; otherwise the record says who began it.
	void Ensure(bool newGame)
	{
		int on = 0;
		CvPreGame::GetGameOption(OPTION, on);
		std::vector<SlSlot> slots(MAX_MAJOR_CIVS);
		std::vector<bool> active(MAX_MAJOR_CIVS, false);
		char key[64];
		_snprintf_s(key, sizeof(key), _TRUNCATE, "%d:%u", on, CvPreGame::mapRandomSeed());
		std::string k = key;
		for(int p = 0; p < MAX_MAJOR_CIVS; ++p)
		{
			SlotStatus st = CvPreGame::slotStatus((PlayerTypes)p);
			slots[p].civ = CvPreGame::civilization((PlayerTypes)p);
			slots[p].leader = CvPreGame::leaderHead((PlayerTypes)p);
			active[p] = st == SS_TAKEN || st == SS_COMPUTER;
			_snprintf_s(key, sizeof(key), _TRUNCATE, ",%d/%d/%d", slots[p].civ, slots[p].leader, active[p] ? 1 : 0);
			k += key;
		}
		std::string path = RecordPath();
		if(newGame)
		{
			FILE* f = 0;
			std::string rec = SlRecordText(slots, active);
			MakeRoot();
			if(fopen_s(&f, path.c_str(), "wb") == 0 && f) { fwrite(rec.data(), 1, rec.size(), f); fclose(f); }
			else Log("could not write %s", path.c_str());
		}
		if(k == s_key) return;
		s_key = k;
		Clear();
		bool fromRecord = false;
		std::vector<SlSlot> none;
		std::vector<int> civs = SlTakingPart(slots, active, newGame ? none : SlRecordParse(ReadAll(path), MAX_MAJOR_CIVS), fromRecord);
		s_part = civs;
		Log("taking part (%s): %d of %d slots", fromRecord ? "as recorded when the game began" : "the slots in play",
		    (int)(MAX_MAJOR_CIVS - std::count(civs.begin(), civs.end(), -1)), (int)MAX_MAJOR_CIVS);
		std::vector<int> leaders(MAX_MAJOR_CIVS, -1);
		for(int p = 0; p < MAX_MAJOR_CIVS; ++p) if(civs[p] >= 0) leaders[p] = slots[p].leader;
		if(on != 1) { WriteAgents(); return; }

		std::vector<std::string> poolTypes = Column("SELECT Type FROM Civilizations WHERE Playable = 1 AND Type IN (SELECT CivilizationType FROM Civilization_Leaders)");
		std::vector<int> pool;
		for(size_t i = 0; i < poolTypes.size(); ++i) { int id = Id(poolTypes[i]); if(id >= 0) pool.push_back(id); }
		std::vector<int> pair = SlPair(civs, pool, CvPreGame::mapRandomSeed());

		s_traits.assign(GC.getNumLeaderHeadInfos(), std::vector<char>());
		s_units.assign(GC.getNumCivilizationInfos(), std::map<int, int>());
		s_buildings.assign(GC.getNumCivilizationInfos(), std::map<int, int>());
		s_freeUnits.assign(GC.getNumCivilizationInfos(), std::map<int, std::pair<int, int> >());
		for(int p = 0; p < MAX_MAJOR_CIVS; ++p)
		{
			if(civs[p] < 0 || pair[p] < 0 || leaders[p] < 0) continue;
			std::string civ1 = TypeOf("Civilizations", civs[p]), civ2 = TypeOf("Civilizations", pair[p]);
			std::string leader1 = TypeOf("Leaders", leaders[p]);
			std::string leader2 = One("SELECT LeaderheadType FROM Civilization_Leaders WHERE CivilizationType = " + Q(civ2));
			if(!SlIsTypeName(civ1) || !SlIsTypeName(civ2) || !SlIsTypeName(leader1) || !SlIsTypeName(leader2)) continue;
			Second s;
			s.player = p; s.civ = civ2; s.leader = leader2;

			// The second's traits merge row by row; what they leave out is only a slot the first's already fill and their bans.
			std::set<std::string> own;
			std::vector<std::string> t1 = Column("SELECT TraitType FROM Leader_Traits WHERE LeaderType = " + Q(leader1));
			for(size_t i = 0; i < t1.size(); ++i)
			{
				if(!SlIsTypeName(t1[i])) continue;
				std::set<std::string> f = Slots(t1[i]);
				own.insert(f.begin(), f.end());
			}
			std::vector<std::string> t2 = Column("SELECT TraitType FROM Leader_Traits WHERE LeaderType = " + Q(leader2));
			for(size_t i = 0; i < t2.size(); ++i)
			{
				if(!SlIsTypeName(t2[i])) continue;
				Piece piece;
				piece.type = t2[i];
				std::set<std::string> f = Slots(t2[i]);
				piece.leftOut = SlLeftOut(own, f, Bans(t2[i]));
				int tid = Id(t2[i]);
				piece.merged = tid >= 0;
				if(!piece.merged) piece.clash = "the trait is not in the game's database";
				if(piece.merged)
				{
					std::vector<char>& v = s_traits[leaders[p]];
					if((int)v.size() <= tid) v.resize(tid + 1, 0);
					v[tid] = 1;
					own.insert(f.begin(), f.end());
				}
				s.traits.push_back(piece);
			}
			Merge("Civilization_UnitClassOverrides", "UnitClassType", "UnitType", "UnitClasses", "Units", "DefaultUnit", civ1, civ2, s_units, s.units);
			Merge("Civilization_BuildingClassOverrides", "BuildingClassType", "BuildingType", "BuildingClasses", "Buildings", "DefaultBuilding", civ1, civ2, s_buildings, s.buildings);
			// The second's free starting units (Nubia's Scout, its Apedemak's Bow), where it starts with more of a class.
			std::vector<SlFreeUnit> gained = SlMergeFreeUnits(FreeUnits(civ1), FreeUnits(civ2));
			int civ1Id = Id(civ1);
			for(size_t k = 0; k < gained.size(); ++k)
			{
				if(civ1Id >= 0 && civ1Id < (int)s_freeUnits.size()) s_freeUnits[civ1Id][gained[k].cls] = std::make_pair(gained[k].count, gained[k].ai);
				Piece start;
				start.type = StartingUnit(civ1, civ1Id, gained[k].cls);
				start.merged = true;
				s.starting.push_back(start);
			}
			s_seconds.push_back(s);
			Log("player %d: %s + %s (%s)", p, civ1.c_str(), civ2.c_str(), leader2.c_str());
		}
		s_on = true;
		WriteAgents();
	}

