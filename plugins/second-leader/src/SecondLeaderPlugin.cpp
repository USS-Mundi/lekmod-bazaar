	std::vector<std::string> Column(const std::string& sql)
	{
		std::vector<std::string> out;
		Database::Results r;
		if(!DB.Execute(r, sql.c_str())) { Log("query failed: %s", sql.c_str()); return out; }
		while(r.Step()) out.push_back(r.GetText(0) ? r.GetText(0) : "");
		return out;
	}

	std::string One(const std::string& sql)
	{
		std::vector<std::string> v = Column(sql);
		return v.empty() ? std::string() : v[0];
	}

	std::string Q(const std::string& type) { return "'" + type + "'"; }

	std::string Text(const std::string& key) { return key.empty() ? std::string() : std::string(GetLocalizedText(key.c_str()).c_str()); }

	int Id(const std::string& type) { return type.empty() ? -1 : GC.getInfoTypeForString(type.c_str(), true); }

	bool HasTable(const std::string& table)
	{
		return SlIsTypeName(table) && !One("SELECT name FROM sqlite_master WHERE type = 'table' AND name = " + Q(table)).empty();
	}

	// What one trait alone can fill, so a second trait cannot share it (the game core keeps the leader's own): the
	// Traits columns it reads as "the first trait that has one", and each build a time override is for.
	std::set<std::string> Slots(const std::string& trait)
	{
		static const char* const COLUMNS[] = { "FreeBuilding", "FreeCapitalBuilding", "FreeBuildingOnConquest", "YieldSettleUnit",
			"CombatBonusImprovement", "FreeBuildingPrereqTech" };
		std::set<std::string> out;
		Database::Results r;
		if(DB.Execute(r, ("SELECT * FROM Traits WHERE Type = " + Q(trait)).c_str()) && r.Step())
			for(int i = 0; i < r.ColumnCount(); ++i)
			{
				std::string col = r.ColumnName(i) ? r.ColumnName(i) : "";
				for(size_t k = 0; k < sizeof(COLUMNS) / sizeof(COLUMNS[0]); ++k)
					if(col == COLUMNS[k] && SlIsSet(r.GetText(i))) out.insert("Traits." + col);
			}
		const char* overrides = "Trait_BuildImprovementBuildTimeOverride";
		if(HasTable(overrides))
		{
			std::vector<std::string> builds = Column(std::string("SELECT BuildType FROM ") + overrides + " WHERE TraitType = " + Q(trait));
			for(size_t i = 0; i < builds.size(); ++i) out.insert(std::string(overrides) + ":" + builds[i]);
		}
		return out;
	}

	// A trait's bans (a unit it may not train, an improvement it may not build, an order its units may not take), which
	// never pass on to the leader it merges into: the game core takes bans from a leader's own traits only.
	std::set<std::string> Bans(const std::string& trait)
	{
		static const char* const TABLES[][2] = { { "Trait_NoTrain", "UnitClassType" }, { "Trait_NoBuildImprovement", "ImprovementType" },
			{ "Trait_BanUnitMissions", "MissionType" } };
		std::set<std::string> out;
		// Venice's no-annexing rule (no Settlers, every new city a puppet) is a Traits column, not a table row.
		if(SlIsSet(One("SELECT NoAnnexing FROM Traits WHERE Type = " + Q(trait)).c_str())) out.insert("Traits.NoAnnexing");
		for(size_t t = 0; t < sizeof(TABLES) / sizeof(TABLES[0]); ++t)
		{
			if(!HasTable(TABLES[t][0])) continue;
			std::vector<std::string> v = Column(std::string("SELECT ") + TABLES[t][1] + " FROM " + TABLES[t][0] + " WHERE TraitType = " + Q(trait));
			for(size_t i = 0; i < v.size(); ++i) out.insert(std::string(TABLES[t][0]) + ":" + v[i]);
		}
		return out;
	}

	// A civilization's free starting units, from Civilization_FreeUnits.
	std::vector<SlFreeUnit> FreeUnits(const std::string& civ)
	{
		std::vector<SlFreeUnit> out;
		Database::Results r;
		if(!DB.Execute(r, ("SELECT UnitClassType, UnitAIType, Count FROM Civilization_FreeUnits WHERE CivilizationType = " + Q(civ)).c_str())) return out;
		while(r.Step())
		{
			SlFreeUnit u;
			u.cls = Id(r.GetText(0) ? r.GetText(0) : "");
			u.ai = Id(r.GetText(1) ? r.GetText(1) : "");
			u.count = r.GetText(2) ? atoi(r.GetText(2)) : 0;
			if(u.cls >= 0 && u.count > 0) out.push_back(u);
		}
		return out;
	}

	std::vector<SlOverride> Overrides(const std::string& table, const std::string& classCol, const std::string& itemCol, const std::string& civ)
	{
		std::vector<SlOverride> out;
		Database::Results r;
		if(!DB.Execute(r, ("SELECT " + classCol + ", " + itemCol + " FROM " + table + " WHERE CivilizationType = " + Q(civ)).c_str())) return out;
		while(r.Step())
		{
			SlOverride o;
			o.cls = Id(r.GetText(0) ? r.GetText(0) : "");
			o.item = Id(r.GetText(1) ? r.GetText(1) : "");
			if(o.cls >= 0) out.push_back(o);
		}
		return out;
	}

	std::string TypeOf(const char* table, int id)
	{
		char sql[160];
		_snprintf_s(sql, sizeof(sql), _TRUNCATE, "SELECT Type FROM %s WHERE ID = %d", table, id);
		return One(sql);
	}

	// ----- deciding -----

	// The unit a merged civilization's free starting unit of a class is: its second's unique for the class where that
	// merged, else its own, else the class's default.
	std::string StartingUnit(const std::string& civ1, int c1, int cls)
	{
		if(c1 >= 0 && c1 < (int)s_units.size() && s_units[c1].count(cls)) return TypeOf("Units", s_units[c1][cls]);
		std::string clsType = TypeOf("UnitClasses", cls);
		std::string own = One("SELECT UnitType FROM Civilization_UnitClassOverrides WHERE CivilizationType = " + Q(civ1) + " AND UnitClassType = " + Q(clsType));
		return own.empty() ? One("SELECT DefaultUnit FROM UnitClasses WHERE Type = " + Q(clsType)) : own;
	}

	void Clear()
	{
		s_on = false;
		s_traits.clear(); s_units.clear(); s_buildings.clear(); s_freeUnits.clear(); s_seconds.clear(); s_part.clear();
	}

	void Merge(const char* table, const char* classCol, const char* itemCol, const char* classTable, const char* itemTable, const char* defaultCol,
	           const std::string& civ1, const std::string& civ2, std::vector<std::map<int, int> >& apply, std::vector<Piece>& pieces)
	{
		int c1 = Id(civ1);
		std::vector<SlMerged> m = SlMergeOverrides(Overrides(table, classCol, itemCol, civ1), Overrides(table, classCol, itemCol, civ2));
		for(size_t i = 0; i < m.size(); ++i)
		{
			Piece p;
			p.type = TypeOf(itemTable, m[i].item);
			std::string cls = TypeOf(classTable, m[i].cls);
			p.replaces = One(std::string("SELECT ") + defaultCol + " FROM " + classTable + " WHERE Type = " + Q(cls));
			p.merged = m[i].merged;
			if(!p.merged) p.clash = cls;
			else if(c1 >= 0 && c1 < (int)apply.size()) apply[c1][m[i].cls] = m[i].item;
			pieces.push_back(p);
		}
	}

